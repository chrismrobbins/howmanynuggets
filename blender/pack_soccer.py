"""Pack blender/render_soccer/*.json (from soccerrig.py) into js/soccerMeshData.js.

    python3 blender/pack_soccer.py
    python3 blender/pack_soccer.py --merge    # add / replace only what's in render_soccer/, keep the rest

--merge is for a session that exported a few models (SOC_ONLY=p.body,ball blender -b -P blender/soccerrig.py):
render_soccer/ is gitignored, so on a fresh checkout it holds only what you just built.

Soccer pieces span from a 0.11 m ball to a 20 m stand, so positions use a PER-MODEL scale: int16 = round(v * s)
with s = floor(32767 / max |coord|) (the model's own precision: ~0.003 mm on a player part, ~0.6 mm on the stand).
The format is documented again at the top of the generated file.
"""
import base64, glob, json, math, os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "render_soccer")
DST = os.path.join(HERE, "..", "js", "soccerMeshData.js")
PSCALE = 8000  # the fallback scale for a model without "s" (none today)
HEAD = "window.SOC_MESH_DATA = { pscale: %d, models: " % PSCALE

DOC = """// ⚽ NUGGET SOCCER — Blender meshes (generated by blender/pack_soccer.py from blender/soccerrig.py; do not edit)
//
// window.SOC_MESH_DATA = { pscale, models: { <name>: M, ... } }   (metres; x right, y up, z forward)
//   M.v    vertex count                M.t  triangle count
//   M.s    this model's position scale: position = int16 / M.s  (M.s = floor(32767 / max|coord|); pscale is only a
//          fallback if a model has no "s")
//   M.b    bbox [minx, miny, minz, maxx, maxy, maxz] in metres
//   M.p    base64 int16 x3 per vertex (÷ M.s)
//   M.n    base64 int8  x3 per vertex (÷ 127), smoothed by angle per material
//   M.c    base64 uint8 x4 per vertex: rgb = flat colour × baked AO; a = TEAM MASK:
//          255 = kit1 (shirt, stand / dugout seats, fan scarves), 128 = kit2 (shorts), 64 = kit3 (socks), 0 = fixed colour.
//          Team surfaces are mid-light greys: keep their luminance, repaint the hue.
//   M.u    base64 uint8 x2 per vertex: (surface class, grime 0..255) — the Nugget Alert class list (alertrig.py)
//   M.i    base64 uint16 x3 per triangle (uint32 when M.big)
"""


def b64(fmt, vals):
    return base64.b64encode(struct.pack("<%d%s" % (len(vals), fmt), *vals)).decode()


def main():
    out = {}
    if "--merge" in sys.argv and os.path.exists(DST):
        txt = open(DST).read()
        at = txt.index(HEAD) + len(HEAD)
        out = json.JSONDecoder().raw_decode(txt[at:])[0]
        print("merging into", len(out), "models")
    for path in sorted(glob.glob(os.path.join(SRC, "*.json"))):
        d = json.load(open(path))
        P = d["p"]
        mx = max(abs(v) for v in P) or 1.0
        s = int(math.floor(32767 / mx))
        p = [max(-32767, min(32767, round(v * s))) for v in P]
        n = [max(-127, min(127, round(v * 127))) for v in d["n"]]
        nv = len(P) // 3
        big = nv > 65535
        bb = [round(min(P[k::3]), 4) for k in range(3)] + [round(max(P[k::3]), 4) for k in range(3)]
        out[d["name"]] = {"v": nv, "t": len(d["i"]) // 3, "s": s, "b": bb, "p": b64("h", p), "n": b64("b", n), "c": b64("B", d["c"]),
                          "u": b64("B", d["u"]), "i": b64("I" if big else "H", d["i"]), "big": big}
    total = sum(M["t"] for M in out.values())
    body = json.dumps(out, separators=(",", ":"))
    with open(DST, "w") as f:
        f.write(DOC)
        f.write(HEAD + body + " };\n")
    print("wrote", os.path.normpath(DST), len(out), "models,", total, "tris,", os.path.getsize(DST) // 1024, "KB")


if __name__ == "__main__":
    main()
