"""Pack blender/render_alert/*.json (from alertrig.py) into js/alertMeshData.js.

    python3 blender/pack_alert.py
    python3 blender/pack_alert.py --merge    # add / replace only what's in render_alert/, keep the rest

--merge is for a session that exported a few models (ALR_ONLY=b.x,b.y blender -b -P blender/alertrig.py):
render_alert/ is gitignored, so on a fresh checkout it holds only what you just built, and a plain pack
would drop every other model from js/alertMeshData.js.

Each model ships as base64 typed arrays: positions int16 (÷ALR_PSCALE tiles), normals int8 (÷127),
colours uint8 rgba (a = team mask), indices uint16 (uint32 past 65535 verts). js/alertArt.js decodes them
into the same {p, n, c, u, i} shape AlrMB.bake() takes. The file is injected only when Nugget Alert
opens (it's a hidden game: nobody else should download it).
"""
import base64, glob, json, os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "render_alert")
DST = os.path.join(HERE, "..", "js", "alertMeshData.js")
PSCALE = 8000  # int16 / 8000 = ±4.09 tiles, 0.000125-tile steps


def b64(fmt, vals):
    return base64.b64encode(struct.pack("<%d%s" % (len(vals), fmt), *vals)).decode()


def main():
    out = {}
    if "--merge" in sys.argv:
        txt = open(DST).read()
        head = "window.ALR_MESH_DATA = { pscale: %d, models: " % PSCALE
        at = txt.index(head) + len(head)
        out = json.JSONDecoder().raw_decode(txt[at:])[0]
        print("merging into", len(out), "models")
    total = 0
    for path in sorted(glob.glob(os.path.join(SRC, "*.json"))):
        d = json.load(open(path))
        p = [max(-32767, min(32767, round(v * PSCALE))) for v in d["p"]]
        n = [max(-127, min(127, round(v * 127))) for v in d["n"]]
        nv = len(d["p"]) // 3
        big = nv > 65535
        out[d["name"]] = {"v": nv, "p": b64("h", p), "n": b64("b", n), "c": b64("B", d["c"]), "u": b64("B", d["u"]),
                          "i": b64("I" if big else "H", d["i"]), "big": big}
    total = sum(len(base64.b64decode(M["i"])) // (4 if M["big"] else 2) // 3 for M in out.values())
    body = json.dumps(out, separators=(",", ":"))
    with open(DST, "w") as f:
        f.write("// 🚨 NUGGET ALERT — Blender meshes (generated by blender/pack_alert.py from blender/alertrig.py; do not edit)\n")
        f.write("window.ALR_MESH_DATA = { pscale: %d, models: %s };\n" % (PSCALE, body))
    print("wrote", DST, len(out), "models,", total, "tris,", os.path.getsize(DST) // 1024, "KB")


if __name__ == "__main__":
    main()
